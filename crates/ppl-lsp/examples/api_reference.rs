//! Generates the handbook API pages from the same metadata and prose as the editor.

use std::{
    collections::{BTreeMap, BTreeSet},
    error::Error,
    fmt::Write as _,
    fs,
    path::PathBuf,
};

use i18n_embed::LanguageLoader;
use icy_board_ppl::{compiler::user_data::UserDataEntry, executable::VariableType, parser::UserTypeRegistry};
use ppl_lsp::{
    LANGUAGE_LOADER,
    documentation::{get_member_documentation, get_member_documentation_with_parameters, get_type_hover_for_version},
    type_lookup::{MemberKind, members_of, static_members_of, type_name},
};
use tower_lsp::lsp_types::HoverContents;
use unicase::Ascii;

type Result<T> = std::result::Result<T, Box<dyn Error>>;

fn behavior(name: &str) -> Result<&'static str> {
    Ok(match name {
        "Board" | "Session" => "board-and-session-400",
        "User" => "the-caller-400",
        "CONTACT" => "notes-and-contacts",
        "MSGHEADER" => "composing-and-editing-messages",
        "Conference" | "Area" | "Directory" | "Door" => "board-objects-400",
        "Bulletin" => "bulletins-and-news-400",
        "Survey" => "introduction-and-surveys-400",
        "Msg" => "messages-400",
        "FileEntry" | "FilePage" => "filebase-search-400",
        "Archive" | "ArchiveOptions" | "ArchiveReader" | "ArchiveEntry" => "reading-archives-400",
        "Terminal" | "TermInfo" => "terminal-information",
        "Gfx" | "Surface" => "graphics",
        "Audio" => "audio",
        "TermInput" | "Event" => "input-and-events",
        "Margins" => "text-margins",
        "Palette" => "palette-colors",
        "Macros" => "terminal-output-macros",
        "Error" => "errors",
        "Http" | "HttpRequest" | "HttpResponse" => "http-objects-400",
        "Regex" | "RegexMatch" => "regular-expressions",
        _ => return Err(format!("Add a behavioral guide for API type {name}").into()),
    })
}

fn header(name: &str, kind: &str) -> String {
    format!(
        "<!-- Generated by ppl-lsp/examples/api_reference.rs; do not edit. -->\n\n\
         # {name}\n\n\
         **PPL language/runtime 4.00 - {kind}.**\n\n\
         [Object model and calling conventions](../objects.md) | [API index](index.md)\n\n"
    )
}

fn pages() -> Result<BTreeMap<String, String>> {
    let registry = UserTypeRegistry::icy_board_registry();
    let mut pages = BTreeMap::new();
    let mut objects = Vec::new();
    let mut records = Vec::new();
    let mut enums = Vec::new();

    for (name, typ) in &registry.registered_types {
        let VariableType::UserData(id) = *typ else { continue };
        if registry.get_enum_from_id(id).is_some() {
            continue;
        }
        let name = name.to_string();
        let object = registry.get_type_from_id(id);
        let record = registry.get_record_type_from_id(id);
        let kind = if record.is_some() { "value record" } else { "host object" };
        let mut page = header(&name, kind);
        let hover = get_type_hover_for_version(*typ, 400).ok_or_else(|| format!("Missing type documentation: {name}"))?;
        let HoverContents::Markup(content) = hover.contents else {
            return Err(format!("Expected Markdown type documentation: {name}").into());
        };
        let (_, prose) = content.value.split_once("\n\n").ok_or("Missing type description")?;
        writeln!(page, "{prose}\n")?;
        if name == "Zip" || name == "ZipWriter" {
            page.push_str("[Behavior, defaults and examples](../zip.md).\n\n");
        } else {
            writeln!(page, "[Behavior, constraints and examples](../../../new_ppl.md#{}).\n", behavior(&name)?)?;
        }
        if object.is_some_and(|object| object.instance_provider.is_some()) {
            writeln!(page, "Use `{name}` or `{name}()` to obtain the current root object.\n")?;
        }
        if name == "User" {
            page.push_str(
                "A writable property still requires a writable handle: `Session.User` and \
                 `Board.FindUser()`/`Board.AddUser()` support changes; `Board.Users` entries \
                 are read-only snapshots. Changes are saved immediately.\n\n",
            );
        }
        if name == "Area" || name == "Msg" {
            page.push_str(
                "```{warning}\n\
                 Message reads do not apply the interactive reader's access/privacy filtering. \
                 The PPE must enforce visibility; `Valid` alone is not an access check. \
                 See [message visibility](../../../new_ppl.md#who-may-see-a-message-is-the-programs-decision).\n\
                 ```\n\n",
            );
        }
        if record.is_some() {
            page.push_str("Fields are writable on the local value; modifying a copy does not write back to the board.\n\n");
        }
        let mut members: BTreeMap<_, _> = members_of(&registry, *typ).into_iter().map(|member| (member.name.clone(), member)).collect();
        for member in static_members_of(&registry, *typ) {
            members.insert(member.name.clone(), member);
        }
        let expected = if let Some(object) = object {
            objects.push(name.clone());
            object.fields.len() + object.functions.len() + object.procedures.len()
        } else if let Some(record) = &record {
            records.push(name.clone());
            record.fields.len()
        } else {
            return Err(format!("Unknown registered API type: {name}").into());
        };
        if members.len() != expected {
            return Err(format!("Incomplete member inventory: {name}, expected {expected}, got {}", members.len()).into());
        }
        for (member_name, member) in members {
            let key = Ascii::new(member_name.clone());
            let statik = object.is_some_and(|object| object.statics.contains(&key));
            writeln!(page, "## {member_name}\n")?;
            match member.kind {
                MemberKind::Field => {
                    let writable = record.is_some()
                        || object.is_some_and(|object| {
                            object
                                .member_id_lookup
                                .get(&key)
                                .and_then(|id| object.id_table.get(*id))
                                .is_some_and(|entry| matches!(entry, UserDataEntry::Field(_)))
                        });
                    let access = if writable { "Writable" } else { "Read-only" };
                    writeln!(
                        page,
                        "`{name}.{member_name}: {}`\n\n{access} {}.\n",
                        member.detail,
                        if record.is_some() { "field" } else { "instance property" }
                    )?;
                }
                MemberKind::Method => {
                    let binding = if statik { "Static" } else { "Instance" };
                    let kind = if object.is_some_and(|object| object.functions.contains_key(&key)) {
                        "function"
                    } else {
                        "procedure (no return value)"
                    };
                    writeln!(page, "```PPL\n{name}.{member_name}{}\n```\n\n{binding} {kind}.\n", member.detail)?;
                }
            }
            let prose = get_member_documentation(*typ, &member_name).ok_or_else(|| format!("Missing member documentation: {name}.{member_name}"))?;
            writeln!(page, "{prose}\n")?;
        }
        let mut related = Vec::new();
        if let Some(object) = object {
            related.extend(object.fields.values().copied());
            for function in object.functions.values() {
                related.extend(&function.parameters);
                related.push(function.return_type);
            }
            for procedure in object.procedures.values() {
                related.extend(&procedure.parameters);
            }
        }
        if let Some(record) = record {
            related.extend(record.fields.iter().map(|(_, field)| field.variable_type));
        }
        let related: BTreeSet<_> = related
            .into_iter()
            .filter(|related| matches!(related, VariableType::UserData(_)) && *related != *typ)
            .map(|related| type_name(&registry, related))
            .collect();
        if !related.is_empty() {
            page.push_str("## Related types\n\n");
            for related in related {
                writeln!(page, "- [{related}]({}.md)", related.to_ascii_lowercase())?;
            }
        }
        pages.insert(format!("{}.md", name.to_ascii_lowercase()), page);
    }
    for definition in registry.enums() {
        let name = definition.name.to_string();
        enums.push(name.clone());
        let mut page = header(&name, "enum");
        page.push_str(
            "Use qualified values rather than raw integers. These are open nominal enums: \
             each enum has its own type, and its known values are listed below. \
             Host operations may reject unknown or unsupported values even though the enum \
             can store them. See [enum rules and bit operations](../../../new_ppl.md#enum--endenum-declaration-350).\n\n",
        );
        let (first, _) = definition.variants.first().ok_or_else(|| format!("Empty enum: {name}"))?;
        writeln!(
            page,
            "The default value is `{name}.{first}` (the first declared member).\n\n\
            ## Values\n\n| Name | Integer value | Meaning |\n| --- | ---: | --- |"
        )?;
        for (variant, value) in &definition.variants {
            let meaning = get_member_documentation(VariableType::UserData(definition.id), variant.as_str())
                .ok_or_else(|| format!("Missing enum documentation: {name}.{variant}"))?;
            writeln!(page, "| `{name}.{variant}` | `{value}` | {} |", meaning.replace('|', "\\|").replace('\n', " "))?;
        }
        writeln!(page, "\n## Has\n\n```PPL\n{name}.Has({name} mask) BOOLEAN\n```\n\nInstance function.\n")?;
        let prose = get_member_documentation_with_parameters(&registry, VariableType::UserData(definition.id), &Ascii::new("Has".into()))
            .ok_or_else(|| format!("Missing enum Has documentation: {name}"))?;
        writeln!(page, "{prose}\n")?;
        pages.insert(format!("{}.md", name.to_ascii_lowercase()), page);
    }
    let mut index = String::from(
        "<!-- Generated by ppl-lsp/examples/api_reference.rs; do not edit. -->\n\n\
         # Complete type and member index\n\n\
         Every registered PPL 4.00 host object, built-in record and enum is listed here. \
         Signatures and descriptions share their sources with the compiler and editor. \
         Start with the [object model](../objects.md) for acquisition, lifetimes, access \
         checks and examples. Square brackets in a parameter list mean optional arguments; \
         brackets following a type describe array rank.\n\n",
    );
    for (heading, mut names) in [("Host objects", objects), ("Value records", records), ("Enums", enums)] {
        names.sort_by_key(|name| name.to_ascii_lowercase());
        writeln!(index, "## {heading}\n\n```{{toctree}}\n:maxdepth: 1\n")?;
        for name in names {
            writeln!(index, "{}", name.to_ascii_lowercase())?;
        }
        index.push_str("```\n\n");
    }
    pages.insert("index.md".into(), index);
    for content in pages.values_mut() {
        content.truncate(content.trim_end().len());
        content.push('\n');
    }
    Ok(pages)
}

fn main() -> Result<()> {
    let args: Vec<_> = std::env::args().skip(1).collect();
    let write = match args.as_slice() {
        [] => false,
        [arg] if arg == "--check" => false,
        [arg] if arg == "--write" => true,
        _ => return Err("Usage: LANGUAGE=en cargo run -p ppl-lsp --example api_reference -- [--check|--write]".into()),
    };
    if LANGUAGE_LOADER.current_language() != "en" {
        return Err("Run the generator in an English process: set LANGUAGE=en".into());
    }
    let pages = pages()?;
    let directory = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../docs/source/ppl/api");
    if write {
        fs::create_dir_all(&directory)?;
    }
    for entry in fs::read_dir(&directory)? {
        let entry = entry?;
        if entry.path().extension().is_some_and(|extension| extension == "md") && !pages.contains_key(&entry.file_name().to_string_lossy().to_string()) {
            return Err(format!("Remove obsolete generated API page: {}", entry.path().display()).into());
        }
    }
    for (name, content) in &pages {
        let path = directory.join(name);
        if write {
            fs::write(path, content)?;
        } else if fs::read_to_string(&path)? != *content {
            return Err(format!("Stale API page: {}; regenerate with --write", path.display()).into());
        }
    }
    println!("{} API pages {}", pages.len(), if write { "generated" } else { "verified" });
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use icy_board_ppl::{
        compiler::{PPECompiler, workspace::Workspace},
        parser::{Encoding, ErrorReporter, board_catalog, parse_ast},
    };
    use std::sync::{Arc, Mutex};

    #[test]
    fn inventory_covers_every_type_member_and_enum() {
        let registry = UserTypeRegistry::icy_board_registry();
        let pages = pages().unwrap();
        assert_eq!(pages.len(), registry.registered_types.len() + registry.enums().len() + 1);
        for &(id, name, _) in board_catalog::TYPES {
            let page = &pages[&format!("{}.md", name.to_ascii_lowercase())];
            let object = registry.get_type_from_id(id as u32).unwrap();
            for member in object.fields.keys().chain(object.functions.keys()).chain(object.procedures.keys()) {
                assert_eq!(page.matches(&format!("## {member}\n")).count(), 1, "{name}.{member}");
            }
        }
        for definition in registry.enums() {
            let page = &pages[&format!("{}.md", definition.name.to_string().to_ascii_lowercase())];
            for (variant, value) in definition.variants {
                assert!(page.contains(&format!("| `{}.{variant}` | `{value}` |", definition.name)));
            }
        }
    }

    #[test]
    fn signatures_and_access_are_preserved_and_output_is_stable() {
        let pages = pages().unwrap();
        assert_eq!(pages, super::pages().unwrap());
        for content in pages.values() {
            assert!(content.ends_with('\n') && !content.ends_with("\n\n"));
        }
        assert!(pages["board.md"].contains("`Board.Conferences: Conference[]`\n\nRead-only"));
        assert!(pages["user.md"].contains("`User.Alias: STRING`\n\nWritable"));
        assert!(pages["user.md"].contains("`User.Uploads: ULONG`\n\nRead-only"));
        assert!(pages["contact.md"].contains("`CONTACT.Account: STRING`\n\nWritable field"));
        assert!(pages["msgheader.md"].contains("`MSGHEADER.IsPrivate: BOOLEAN`\n\nWritable field"));
        assert!(pages["regex.md"].contains("Regex.FindAll(STRING text, [INTEGER start], [INTEGER limit]) RegexMatch[]"));
        assert!(pages["archive.md"].contains("Archive.Open(STRING path, [ArchiveOptions options]) ArchiveReader\n```\n\nStatic function."));
        assert!(pages["zipwriter.md"].contains("ZipWriter.AddTree(STRING sourceDirectory, [STRING prefix], [BOOLEAN recursive]) BOOLEAN"));
    }

    #[test]
    fn handbook_examples_compile_for_runtime_400() {
        let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../docs/source/ppl");
        let mut count = 0;
        for file in ["objects.md", "zip.md"] {
            let markdown = fs::read_to_string(root.join(file)).unwrap();
            for block in markdown.split("```PPL\n").skip(1) {
                let source = block.split_once("\n```").unwrap().0;
                let mut workspace = Workspace::default();
                workspace.package.runtime = Some(400);
                workspace.set_default_language_version(Some(400));
                let registry = UserTypeRegistry::icy_board_registry();
                let errors = Arc::new(Mutex::new(ErrorReporter::default()));
                let ast = parse_ast(PathBuf::from(file), errors.clone(), source, &registry, Encoding::Utf8, &workspace);
                let mut compiler = PPECompiler::new(&workspace, registry, errors.clone());
                compiler.compile(&[&ast]);
                let errors = errors.lock().unwrap();
                let messages: Vec<_> = errors.errors.iter().map(|error| error.error.to_string()).collect();
                assert!(!errors.has_errors(), "{file}: {messages:?}");
                compiler.create_executable().unwrap();
                count += 1;
            }
        }
        assert_eq!(count, 2, "Keep both complete handbook examples under test");
    }
}
